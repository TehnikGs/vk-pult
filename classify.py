# минимум очков, чтобы вообще что-то утверждать
MIN_SCORE = 3


def _score(text: str, table: dict) -> tuple[int, list[str]]:
    hits, total = [], 0
    for weight, words in table.items():
        for w in words:
            if w in text:
                total += weight
                hits.append(w.strip())
    return total, hits


def classify(text: str, attachments=None) -> dict:
    """Возвращает {'kind', 'score', 'confidence', 'hits', 'second'}."""
    t = " " + re.sub(r"\s+", " ", (text or "").lower()).replace("ё", "ё") + " "
    results = {}
    for kind, table in GROUPS.items():
        score, hits = _score(t, table)
        if score:
            results[kind] = (score, hits)

    if not results:
        return {"kind": "news", "score": 0, "confidence": 0.0, "hits": [], "second": None}

    order = sorted(results.items(), key=lambda kv: kv[1][0], reverse=True)
    best_kind, (best_score, best_hits) = order[0]
    second = order[1][0] if len(order) > 1 else None
    second_score = order[1][1][0] if len(order) > 1 else 0

    if best_score < MIN_SCORE:
        return {"kind": "news", "score": best_score, "confidence": 0.0,
                "hits": best_hits, "second": best_kind}

    # уверенность: и сколько набрал, и насколько оторвался от второго
    gap = (best_score - second_score) / best_score
    confidence = min(1.0, (best_score / 10) * 0.6 + gap * 0.4)

    # «продам щенка» — это продажа животного, а не потеряшка
    if best_kind == "pets" and "market" in results:
        sell = any(w in t for w in ("продам", "продаю", "продается", "продаётся", "цена"))
        if sell and "в добрые руки" not in t:
            return {"kind": "market", "score": results["market"][0],
                    "confidence": min(confidence, 0.7), "hits": results["market"][1],
                    "second": "pets"}

    return {"kind": best_kind, "score": best_score, "confidence": round(confidence, 2),
            "hits": best_hits[:6], "second": second}


