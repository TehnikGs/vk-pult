def main():
    db = sqlite3.connect(DB)
    CL.init(db)
    db.execute("DELETE FROM clients")
    db.execute("DELETE FROM pins")
    db.execute("DELETE FROM reminders_sent")
    db.commit()

    for name, posts, note in POSTS:
        CL.add_client(db, name, posts, note)
    for d_from, d_to, paid, who, note in PINS:
        CL.add_pin(db, who, d_from, d_to, paid, note)

    print("клиентов:", len(POSTS), "· закрепов:", len(PINS))
    print()
    print(CL.clients_text(db).replace("<b>", "").replace("</b>", "")
          .replace("<i>", "").replace("</i>", ""))
    print()
    print(CL.pins_text(db).replace("<b>", "").replace("</b>", "")
          .replace("<i>", "").replace("</i>", ""))
    db.close()


if __name__ == "__main__":
    main()
